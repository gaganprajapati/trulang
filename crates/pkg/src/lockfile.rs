//! Tru.lock Cryptographic Hermetic Lockfile Generator and Verifier.
//!
//! Generates bit-for-bit reproducible SHA-256 tree hashes guaranteeing identical
//! builds across developer machines and production CI/CD pipelines.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    pub source: String,
    pub checksum: String,
    #[serde(default)]
    pub dependencies: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Lockfile {
    pub version: String,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

impl Lockfile {
    pub const FILE_NAME: &'static str = "Tru.lock";
    pub const CURRENT_VERSION: &'static str = "1.0.0";

    pub fn new() -> Self {
        Self {
            version: Self::CURRENT_VERSION.to_string(),
            packages: Vec::new(),
        }
    }

    pub fn from_file(path: impl AsRef<Path>) -> anyhow::Result<Self> {
        let content = fs::read_to_string(path)?;
        Self::from_str(&content)
    }

    pub fn from_str(content: &str) -> anyhow::Result<Self> {
        let lockfile: Self = toml::from_str(content)?;
        Ok(lockfile)
    }

    pub fn to_string(&self) -> anyhow::Result<String> {
        let header = "# Auto-generated by TruLang Package Manager (tpm). Do not edit manually.\n";
        let body = toml::to_string_pretty(self)?;
        Ok(format!("{}{}", header, body))
    }

    pub fn write_to_file(&self, path: impl AsRef<Path>) -> anyhow::Result<()> {
        let s = self.to_string()?;
        fs::write(path, s)?;
        Ok(())
    }

    pub fn find_package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    pub fn upsert_package(&mut self, pkg: LockedPackage) {
        if let Some(pos) = self.packages.iter().position(|p| p.name == pkg.name) {
            self.packages[pos] = pkg;
        } else {
            self.packages.push(pkg);
        }
        self.packages.sort_by(|a, b| a.name.cmp(&b.name));
    }

    pub fn verify_package(&self, pkg_name: &str, dir: &Path) -> anyhow::Result<bool> {
        let pkg = match self.find_package(pkg_name) {
            Some(p) => p,
            None => anyhow::bail!("Package '{}' not found in Tru.lock", pkg_name),
        };

        let calculated_hash = compute_directory_sha256(dir)?;
        Ok(calculated_hash == pkg.checksum)
    }
}

impl Default for Lockfile {
    fn default() -> Self {
        Self::new()
    }
}

/// Computes a deterministic cryptographic SHA-256 hash for a single file.
pub fn compute_file_sha256(path: impl AsRef<Path>) -> io::Result<String> {
    let bytes = fs::read(path)?;
    let mut hasher = Sha256::new();
    hasher.update(&bytes);
    let result = hasher.finalize();
    Ok(format!("sha256:{:x}", result))
}

/// Computes a deterministic directory tree hash by recursively hashing
/// all files in sorted relative path order.
pub fn compute_directory_sha256(dir: impl AsRef<Path>) -> io::Result<String> {
    let dir = dir.as_ref();
    if !dir.exists() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            "Directory not found",
        ));
    }

    let mut files = Vec::new();
    collect_files_recursive(dir, dir, &mut files)?;
    files.sort();

    let mut hasher = Sha256::new();
    for (rel_path, abs_path) in files {
        hasher.update(rel_path.as_bytes());
        let file_bytes = fs::read(abs_path)?;
        hasher.update(&file_bytes);
    }

    let result = hasher.finalize();
    Ok(format!("sha256:{:x}", result))
}

fn collect_files_recursive(
    base: &Path,
    current: &Path,
    out: &mut Vec<(String, PathBuf)>,
) -> io::Result<()> {
    for entry in fs::read_dir(current)? {
        let entry = entry?;
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();

        // Skip git metadata and build artifacts
        if name == ".git" || name == "target" || name == "node_modules" {
            continue;
        }

        if path.is_dir() {
            collect_files_recursive(base, &path, out)?;
        } else if path.is_file() {
            let rel = path.strip_prefix(base).unwrap_or(&path);
            let rel_str = rel.to_string_lossy().to_string();
            out.push((rel_str, path));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lockfile_serialization_and_verification() {
        let temp_dir =
            std::env::temp_dir().join(format!("trulang_lock_test_{}", std::process::id()));
        let _ = fs::remove_dir_all(&temp_dir);
        fs::create_dir_all(&temp_dir).expect("Create dir failed");

        let test_file = temp_dir.join("main.tr");
        fs::write(&test_file, "fn main() { return 42; }").expect("Write test file failed");

        let hash = compute_directory_sha256(&temp_dir).expect("Hash computed");
        assert!(hash.starts_with("sha256:"));

        let mut lockfile = Lockfile::new();
        lockfile.upsert_package(LockedPackage {
            name: "test-pkg".to_string(),
            version: "1.0.0".to_string(),
            source: "local".to_string(),
            checksum: hash.clone(),
            dependencies: Vec::new(),
        });

        let serialized = lockfile.to_string().expect("Serialize success");
        let parsed = Lockfile::from_str(&serialized).expect("Parse success");
        assert!(parsed
            .verify_package("test-pkg", &temp_dir)
            .expect("Verification success"));

        let _ = fs::remove_dir_all(&temp_dir);
    }
}
